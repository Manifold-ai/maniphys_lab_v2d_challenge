"""Render the Tier 3 version registry (runs/VERSIONS.md) from versions.json and what is on disk (plain python3).

versions.json (next to this file) is where each version's status and purpose are written; this adds what the
version dirs say about themselves (episode counts, sidecar records, .provenance.json: script, source version, commit)
and checks the two agree: every version dir under runs/ and runs/archive/ is registered, every registered version is
where its status says (archived under archive/, the rest at the top), and the rxzhou-whitelisted ones ("kept") are in
place. Disagreements are listed at the top of the file and make the exit status 1.

    python3 t3_versions.py <tier3 root> > <tier3 root>/runs/VERSIONS.md
"""

import json
import sys
from pathlib import Path

PREFIX = "tier3_cari4d_f830_"
ORDER = ("delivered", "candidate", "kept", "archived")


def full(name: str) -> str:
    return name if name.startswith("tier3_") else PREFIX + name


def main() -> int:
    root = Path(sys.argv[1])
    runs = root / "runs"
    reg = json.loads((Path(__file__).resolve().parent / "versions.json").read_text())
    versions = reg["versions"]
    problems = []
    on_disk = {}
    for where, base in (("top", runs), ("archive", runs / "archive")):
        for d in sorted(base.glob("tier3_*")):
            if d.is_dir() and not d.name.endswith("_suspect"):
                on_disk[d.name] = (where, d)
    known = {full(k): k for k in versions}
    for name in on_disk:
        if name not in known:
            problems.append(f"`{name}` is on disk ({on_disk[name][0]}) but not in versions.json")
    rows = {s: [] for s in ORDER}
    for key, v in versions.items():
        name = full(key)
        where, d = on_disk.get(name, (None, None))
        want = "archive" if v["status"] == "archived" else "top"
        if where is None:
            problems.append(f"`{key}` is registered ({v['status']}) but not on disk")
        elif where != want:
            problems.append(f"`{key}` is {v['status']} but sits in {where}")
        n = len(list((d / "data" / "chunk-000").glob("*.parquet"))) if d else 0
        sus = d.parent / f"{d.name}_suspect" if d else None
        ns = len(list((sus / "data" / "chunk-000").glob("*.parquet"))) if sus and sus.is_dir() else 0
        side = sorted(p.name[len(name) + 1:] for p in d.parent.glob(f"{name}.*.json")) if d else []
        prov = {}
        if d and (d.parent / f"{name}.provenance.json").exists():
            prov = json.loads((d.parent / f"{name}.provenance.json").read_text())
        made = f"{prov.get('made_by', '')} @ {prov.get('deployed', '')[:7]}" if prov else ""
        rows[v["status"]].append(f"| `{key}` | {v['date']} | {n}+{ns} | {v['from']} | {v['purpose']} | {made} | {', '.join(side)} |")
    for k in reg["work"]:
        if not (runs / k).is_dir():
            problems.append(f"work dir `{k}` is registered but not on disk")
    out = ["# Tier 3 versions", "",
           f"Generated by `stages/recovery/tier3/t3_versions.py` from `versions.json` (the one place statuses and purposes are written) "
           f"and the version dirs. Names drop `{PREFIX}` where it applies. Episodes = main + `_suspect`. Archived versions are under "
           "`runs/archive/` (their gate copies under `gate/archive/`; every move in `archive/MOVED.tsv`). `kept` = read by name by "
           "rxzhou's tools; never move or rename.", ""]
    if problems:
        out += ["## Disagreements", ""] + [f"- {p}" for p in problems] + [""]
    for s in ORDER:
        out += [f"## {s} ({len(rows[s])})", "", "| version | date | episodes | from | purpose | made by @ deployed | records |",
                "|---|---|---|---|---|---|---|"] + rows[s] + [""]
    out += ["## Work dirs (CARI4D runs)", ""] + [f"- `runs/{k}`: {v}" for k, v in reg["work"].items()]
    print("\n".join(out))
    if problems:
        print("\n".join(problems), file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
